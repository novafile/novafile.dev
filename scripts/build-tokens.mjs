// Turns tokens/tokens.json (W3C Design Tokens format) into CSS custom properties
// and a typed module for Storybook's token docs.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(readFileSync(join(root, 'tokens/tokens.json'), 'utf8'));
const MODES = 'dev.novafile.modes';

/** @type {{ path: string[], type: string, value: unknown, dark?: unknown, description?: string }[]} */
const tokens = [];

function walk(node, path, inheritedType) {
	const type = node.$type ?? inheritedType;
	if ('$value' in node) {
		tokens.push({
			path,
			type,
			value: node.$value,
			dark: node.$extensions?.[MODES]?.dark,
			description: node.$description
		});
		return;
	}
	for (const [key, child] of Object.entries(node)) {
		if (key.startsWith('$')) continue;
		walk(child, [...path, key], type);
	}
}
walk(source, [], undefined);

const cssVar = (path) => `--nv-${path.join('-')}`;
const cssValue = (type, value) => {
	if (type === 'fontFamily' && Array.isArray(value)) {
		return value.map((f) => (/[\s]/.test(f) ? `"${f}"` : f)).join(', ');
	}
	return String(value);
};

const light = tokens.map((t) => `\t${cssVar(t.path)}: ${cssValue(t.type, t.value)};`).join('\n');
const dark = tokens
	.filter((t) => t.dark !== undefined)
	.map((t) => `\t${cssVar(t.path)}: ${cssValue(t.type, t.dark)};`)
	.join('\n');
const indent = (s) => s.replace(/^/gm, '\t');

const css = `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */

:root {
${light}
	color-scheme: light;
}

:root[data-theme='dark'] {
${dark}
	color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
	:root:not([data-theme='light']) {
${indent(dark)}
		color-scheme: dark;
	}
}
`;

const ts = `// Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit.

export interface DesignToken {
	name: string;
	group: string;
	cssVar: string;
	type: string;
	value: string;
	dark?: string;
	description?: string;
}

export const tokens: DesignToken[] = ${JSON.stringify(
	tokens.map((t) => ({
		name: t.path.slice(1).join('-'),
		group: t.path[0],
		cssVar: cssVar(t.path),
		type: t.type,
		value: cssValue(t.type, t.value),
		...(t.dark !== undefined ? { dark: cssValue(t.type, t.dark) } : {}),
		...(t.description ? { description: t.description } : {})
	})),
	null,
	'\t'
)};
`;

mkdirSync(join(root, 'src/lib/styles'), { recursive: true });
mkdirSync(join(root, 'src/lib/tokens'), { recursive: true });
writeFileSync(join(root, 'src/lib/styles/tokens.css'), css);
writeFileSync(join(root, 'src/lib/tokens/tokens.generated.ts'), ts);
console.log(
	`tokens: ${tokens.length} tokens, ${tokens.filter((t) => t.dark).length} with a dark value`
);
